create or replace function public.is_teacher()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'teacher');
$$;

create or replace function public.is_subject_teacher(requested_subject_id bigint)
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.subjects
    where id = requested_subject_id and teacher_id = auth.uid()
  ) or exists (
    select 1
    from public.subjects s
    join public.profiles p on p.id = auth.uid()
    where s.id = requested_subject_id
      and s.code = 'ECC12'
      and p.role = 'teacher'
      and p.full_name = 'Mr. Vanie Santos'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    coalesce(
      (select role from public.account_allowlist where lower(email) = lower(new.email) limit 1),
      case when exists (
        select 1 from public.teacher_allowlist
        where lower(email) = lower(new.email)
      ) then 'teacher' else 'student' end
    )
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

