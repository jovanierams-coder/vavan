create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'student' check (role in ('student', 'teacher', 'admin')),
  student_id text,
  section text,
  program text,
  year_level text,
  enrollment_status text not null default 'active' check (enrollment_status in ('active', 'dropped_out')),
  phone text,
  guardian_name text,
  guardian_phone text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  teacher_id uuid references public.profiles(id) on delete set null,
  term text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.grades (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  grade numeric(5,2) not null check (grade between 0 and 100),
  gpa numeric(4,2),
  attendance numeric(5,2) check (attendance between 0 and 100),
  remarks text,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  unique(student_id, subject_id)
);

create table if not exists public.enrollments (
  student_id uuid not null references public.profiles(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  enrollment_status text not null default 'active' check (enrollment_status in ('active', 'dropped_out')),
  enrolled_at timestamptz not null default now(),
  primary key (student_id, subject_id)
);

create table if not exists public.teacher_allowlist (
  email text primary key,
  created_at timestamptz not null default now()
);

create table if not exists public.account_allowlist (
  email text primary key,
  role text not null check (role in ('student', 'teacher', 'admin')),
  created_at timestamptz not null default now()
);

